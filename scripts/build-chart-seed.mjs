// Writes supabase/seed/popular-charts.sql from supabase/seed/popular-charts.js: `npm run seed:charts`.
// Every chart is checked with the app's own validator first, so the SQL only holds charts the app can play.
import { writeFileSync } from 'node:fs'
import { STYLES } from '../src/lib/arranger.js'
import { validateChart } from '../src/lib/chart.js'
import { POPULAR_CHARTS } from '../supabase/seed/popular-charts.js'

const quote = (s) => `'${String(s).replace(/'/g, "''")}'`
const rows = POPULAR_CHARTS.map((draft) => {
  const { chart, error } = validateChart(draft, STYLES)
  if (error) throw new Error(`${draft.title}: ${error}`)
  for (const field of ['style', 'key', 'time', 'tempo'])
    if (chart[field] !== draft[field]) throw new Error(`${draft.title}: ${field} "${draft[field]}" isn't one the app offers`)
  const values = [chart.title, chart.composer, chart.style, chart.key, chart.time, chart.tempo, JSON.stringify(chart.sections), draft.collection]
  return `  (${values.map((v, i) => (i === 5 ? v : i === 6 ? `${quote(v)}::jsonb` : quote(v))).join(', ')})`
})

const sql = `-- ${POPULAR_CHARTS.length} popular charts for the shared catalog, generated by \`npm run seed:charts\`
-- from supabase/seed/popular-charts.js. Run once in the Supabase SQL Editor after charts.sql.
-- Safe to run again: charts whose title is already in the catalog are skipped.

-- Genre shelf for the Charts page filters. Charts visitors share have none and show under "Shared".
alter table public.charts add column if not exists collection text not null default ''
  check (char_length(collection) <= 30);
grant select (collection) on public.charts to anon;

-- Count only charts visitors shared towards the flood limit, so seeding doesn't lock sharing for 10 minutes.
create or replace function public.charts_rate_limit() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  if (select count(*) from public.charts where owner_token is not null and created_at > now() - interval '10 minutes') >= 20 then
    raise exception 'Too many new charts, slow down';
  end if;
  return new;
end;
$$;
revoke all on function public.charts_rate_limit() from public, anon, authenticated;

-- The flood limit would stop a bulk insert, so switch it off just for this.
alter table public.charts disable trigger charts_rate_limit;

insert into public.charts (title, composer, style, key, time_signature, tempo, sections, collection)
select v.title, v.composer, v.style, v.key, v.time_signature, v.tempo, v.sections, v.collection
from (values
${rows.join(',\n')}
) as v (title, composer, style, key, time_signature, tempo, sections, collection)
where not exists (select 1 from public.charts c where lower(c.title) = lower(v.title));

alter table public.charts enable trigger charts_rate_limit;
`
writeFileSync(new URL('../supabase/seed/popular-charts.sql', import.meta.url), sql)
console.log(`Wrote ${rows.length} charts to supabase/seed/popular-charts.sql`)
